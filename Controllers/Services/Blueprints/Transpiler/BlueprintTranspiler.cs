using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using BlockoutStudio.Models.Blueprints;

namespace BlockoutStudio.Services.Blueprints.Transpiler;

/// <summary>
/// High-performance AST walker and C# 13 code generator translating visual Blueprint graphs
/// into readable, strongly-typed C# classes compiling against .NET 10.
/// </summary>
public partial class BlueprintTranspiler : IBlueprintTranspiler
{
    [GeneratedRegex(@"[^a-zA-Z0-9_]")]
    private static partial Regex SanitizeIdentifierRegex();

    public string TranspileToCSharp(BlueprintGraph graph)
    {
        ArgumentNullException.ThrowIfNull(graph);

        var className = SanitizeIdentifier(graph.Name);
        if (string.IsNullOrWhiteSpace(className)) className = "GeneratedBlueprint";

        var baseClass = graph.Type == BlueprintGraphType.Level ? "LevelBlueprint" : "ActorBlueprint";

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"// Transpiled from Blockout Studio Blueprint: {graph.Name}");
        sb.AppendLine($"// Generated at: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine("using BlockoutStudio.Services.Blueprints.Runtime;");
        sb.AppendLine();
        sb.AppendLine("namespace BlockoutStudio.Generated;");
        sb.AppendLine();
        sb.AppendLine($"public class {className} : {baseClass}");
        sb.AppendLine("{");

        // 1. Emit Variables
        if (graph.Variables.Count > 0)
        {
            sb.AppendLine("    // ========================================================================");
            sb.AppendLine("    // Blueprint Member Variables");
            sb.AppendLine("    // ========================================================================");
            foreach (var variable in graph.Variables)
            {
                var varName = SanitizeIdentifier(variable.Name);
                var varType = MapPinTypeToCSharp(variable.Type);
                var defaultLiteral = FormatDefaultLiteral(variable.DefaultValue, variable.Type);
                var access = variable.IsPublic ? "public" : "private";
                sb.AppendLine($"    {access} {varType} {varName} {{ get; set; }} = {defaultLiteral};");
            }
            sb.AppendLine();
        }

        // Index connections by FromPin and ToPin
        var connectionsFromPin = graph.Connections
            .GroupBy(c => $"{c.FromNodeId}_{c.FromPinId}")
            .ToDictionary(g => g.Key, g => g.ToList());

        var connectionsToPin = graph.Connections
            .GroupBy(c => $"{c.ToNodeId}_{c.ToPinId}")
            .ToDictionary(g => g.Key, g => g.First());

        var nodeMap = graph.Nodes.ToDictionary(n => n.Id, n => n);

        // 2. Discover Entry Events
        var eventNodes = graph.Nodes.Where(n => n.Category == BlueprintNodeCategory.Event).ToList();

        // OnBeginPlay
        var beginPlayNodes = eventNodes.Where(n => n.NodeType.Equals("EventBeginPlay", StringComparison.OrdinalIgnoreCase)).ToList();
        sb.AppendLine("    public override void OnBeginPlay()");
        sb.AppendLine("    {");
        sb.AppendLine("        base.OnBeginPlay();");
        foreach (var bpNode in beginPlayNodes)
        {
            var execOut = bpNode.Outputs.FirstOrDefault(p => p.Type == BlueprintPinType.Exec);
            if (execOut != null)
            {
                EmitExecutionChain(sb, 2, bpNode, execOut, nodeMap, connectionsFromPin, connectionsToPin);
            }
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // OnTick
        var tickNodes = eventNodes.Where(n => n.NodeType.Equals("EventTick", StringComparison.OrdinalIgnoreCase)).ToList();
        sb.AppendLine("    public override void OnTick(float deltaSeconds)");
        sb.AppendLine("    {");
        sb.AppendLine("        base.OnTick(deltaSeconds);");
        foreach (var tickNode in tickNodes)
        {
            var execOut = tickNode.Outputs.FirstOrDefault(p => p.Type == BlueprintPinType.Exec);
            if (execOut != null)
            {
                EmitExecutionChain(sb, 2, tickNode, execOut, nodeMap, connectionsFromPin, connectionsToPin);
            }
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // OnCollisionEnter (Actor Blueprint only)
        if (graph.Type == BlueprintGraphType.Actor)
        {
            var collisionNodes = eventNodes.Where(n => n.NodeType.Equals("OnCollisionEnter", StringComparison.OrdinalIgnoreCase)).ToList();
            if (collisionNodes.Count > 0)
            {
                sb.AppendLine("    public override void OnCollisionEnter(Actor other)");
                sb.AppendLine("    {");
                sb.AppendLine("        base.OnCollisionEnter(other);");
                foreach (var colNode in collisionNodes)
                {
                    var execOut = colNode.Outputs.FirstOrDefault(p => p.Type == BlueprintPinType.Exec);
                    if (execOut != null)
                    {
                        EmitExecutionChain(sb, 2, colNode, execOut, nodeMap, connectionsFromPin, connectionsToPin);
                    }
                }
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            var triggerNodes = eventNodes.Where(n => n.NodeType.Equals("OnTriggerEnter", StringComparison.OrdinalIgnoreCase)).ToList();
            if (triggerNodes.Count > 0)
            {
                sb.AppendLine("    public override void OnTriggerEnter(Actor other)");
                sb.AppendLine("    {");
                sb.AppendLine("        base.OnTriggerEnter(other);");
                foreach (var trigNode in triggerNodes)
                {
                    var execOut = trigNode.Outputs.FirstOrDefault(p => p.Type == BlueprintPinType.Exec);
                    if (execOut != null)
                    {
                        EmitExecutionChain(sb, 2, trigNode, execOut, nodeMap, connectionsFromPin, connectionsToPin);
                    }
                }
                sb.AppendLine("    }");
                sb.AppendLine();
            }
        }

        // Custom Events
        var customEvents = eventNodes.Where(n => n.NodeType.Equals("CustomEvent", StringComparison.OrdinalIgnoreCase)).ToList();
        foreach (var ceNode in customEvents)
        {
            var evtName = ceNode.Properties.TryGetValue("EventName", out var en) && !string.IsNullOrWhiteSpace(en)
                ? SanitizeIdentifier(en)
                : $"Custom_{ceNode.Id[..6]}";

            sb.AppendLine($"    public void {evtName}()");
            sb.AppendLine("    {");
            var execOut = ceNode.Outputs.FirstOrDefault(p => p.Type == BlueprintPinType.Exec);
            if (execOut != null)
            {
                EmitExecutionChain(sb, 2, ceNode, execOut, nodeMap, connectionsFromPin, connectionsToPin);
            }
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private void EmitExecutionChain(
        StringBuilder sb,
        int indentLevel,
        BlueprintNode sourceNode,
        BlueprintPin sourceExecPin,
        Dictionary<string, BlueprintNode> nodeMap,
        Dictionary<string, List<BlueprintConnection>> connectionsFromPin,
        Dictionary<string, BlueprintConnection> connectionsToPin)
    {
        var key = $"{sourceNode.Id}_{sourceExecPin.Id}";
        if (!connectionsFromPin.TryGetValue(key, out var connections)) return;

        var visitedInChain = new HashSet<string>();

        foreach (var conn in connections)
        {
            if (!nodeMap.TryGetValue(conn.ToNodeId, out var targetNode)) continue;
            EmitNodeStatement(sb, indentLevel, targetNode, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
        }
    }

    private void EmitNodeStatement(
        StringBuilder sb,
        int indentLevel,
        BlueprintNode node,
        Dictionary<string, BlueprintNode> nodeMap,
        Dictionary<string, List<BlueprintConnection>> connectionsFromPin,
        Dictionary<string, BlueprintConnection> connectionsToPin,
        HashSet<string> visitedInChain)
    {
        if (visitedInChain.Contains(node.Id))
        {
            // Prevent accidental infinite cyclic loops in sequential exec flow
            return;
        }
        visitedInChain.Add(node.Id);

        var indent = new string(' ', indentLevel * 4);

        switch (node.NodeType)
        {
            case "Branch":
                {
                    var condExpr = ResolveInputPinExpression(node, "Condition", BlueprintPinType.Boolean, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}if ({condExpr})");
                    sb.AppendLine($"{indent}{{");
                    var truePin = node.Outputs.FirstOrDefault(p => p.Name.Equals("True", StringComparison.OrdinalIgnoreCase));
                    if (truePin != null)
                    {
                        EmitExecutionChain(sb, indentLevel + 1, node, truePin, nodeMap, connectionsFromPin, connectionsToPin);
                    }
                    sb.AppendLine($"{indent}}}");

                    var falsePin = node.Outputs.FirstOrDefault(p => p.Name.Equals("False", StringComparison.OrdinalIgnoreCase));
                    if (falsePin != null && connectionsFromPin.ContainsKey($"{node.Id}_{falsePin.Id}"))
                    {
                        sb.AppendLine($"{indent}else");
                        sb.AppendLine($"{indent}{{");
                        EmitExecutionChain(sb, indentLevel + 1, node, falsePin, nodeMap, connectionsFromPin, connectionsToPin);
                        sb.AppendLine($"{indent}}}");
                    }
                }
                break;

            case "Sequence":
                {
                    var thenPins = node.Outputs.Where(p => p.Type == BlueprintPinType.Exec).OrderBy(p => p.Name).ToList();
                    foreach (var thenPin in thenPins)
                    {
                        EmitExecutionChain(sb, indentLevel, node, thenPin, nodeMap, connectionsFromPin, connectionsToPin);
                    }
                }
                break;

            case "ForLoop":
                {
                    var firstIdx = ResolveInputPinExpression(node, "FirstIndex", BlueprintPinType.Integer, nodeMap, connectionsToPin);
                    var lastIdx = ResolveInputPinExpression(node, "LastIndex", BlueprintPinType.Integer, nodeMap, connectionsToPin);
                    var loopVar = $"idx_{node.Id[..6]}";

                    sb.AppendLine($"{indent}for (int {loopVar} = {firstIdx}; {loopVar} <= {lastIdx}; {loopVar}++)");
                    sb.AppendLine($"{indent}{{");
                    var loopBody = node.Outputs.FirstOrDefault(p => p.Name.Equals("LoopBody", StringComparison.OrdinalIgnoreCase));
                    if (loopBody != null)
                    {
                        EmitExecutionChain(sb, indentLevel + 1, node, loopBody, nodeMap, connectionsFromPin, connectionsToPin);
                    }
                    sb.AppendLine($"{indent}}}");

                    var completedPin = node.Outputs.FirstOrDefault(p => p.Name.Equals("Completed", StringComparison.OrdinalIgnoreCase));
                    if (completedPin != null)
                    {
                        EmitExecutionChain(sb, indentLevel, node, completedPin, nodeMap, connectionsFromPin, connectionsToPin);
                    }
                }
                break;

            case "SetActorLocation":
                {
                    var locExpr = ResolveInputPinExpression(node, "NewLocation", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}SetActorLocation({locExpr});");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            case "SetActorRotation":
                {
                    var rotExpr = ResolveInputPinExpression(node, "NewRotation", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}SetActorRotation({rotExpr});");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            case "AddActorWorldOffset":
                {
                    var deltaLoc = ResolveInputPinExpression(node, "DeltaLocation", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}AddActorWorldOffset({deltaLoc});");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            case "AddActorWorldRotation":
                {
                    var deltaRot = ResolveInputPinExpression(node, "DeltaRotation", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}AddActorWorldRotation({deltaRot});");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            case "SetVariable":
                {
                    var varName = node.Properties.TryGetValue("VariableName", out var vn) ? SanitizeIdentifier(vn) : "Variable";
                    var valExpr = ResolveInputPinExpression(node, "Value", BlueprintPinType.Float, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}{varName} = {valExpr};");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            case "PlaySound2D":
                {
                    var sound = ResolveInputPinExpression(node, "Sound", BlueprintPinType.String, nodeMap, connectionsToPin);
                    var volume = ResolveInputPinExpression(node, "Volume", BlueprintPinType.Float, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}PlaySound2D({sound}, {volume});");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            case "PrintString":
                {
                    var text = ResolveInputPinExpression(node, "InString", BlueprintPinType.String, nodeMap, connectionsToPin);
                    sb.AppendLine($"{indent}PrintString({text});");
                    EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                }
                break;

            default:
                // Handle dynamic / reflected method call
                if (node.Inputs.Any(p => p.Type != BlueprintPinType.Exec) || node.NodeType.Contains('.'))
                {
                    var dataInputs = node.Inputs.Where(p => p.Type != BlueprintPinType.Exec).ToList();
                    var argExprs = dataInputs.Select(p => ResolveInputPinExpression(node, p.Name, p.Type, nodeMap, connectionsToPin));
                    var argsStr = string.Join(", ", argExprs);
                    var methodName = node.NodeType.Contains('.') ? node.NodeType.Substring(node.NodeType.LastIndexOf('.') + 1) : node.NodeType;
                    var declaring = node.Properties.TryGetValue("DeclaringTypeShort", out var dt) ? dt : "";
                    var isStatic = node.Properties.TryGetValue("IsStatic", out var isSt) && isSt == "true";

                    var callPrefix = isStatic && !string.IsNullOrEmpty(declaring) ? $"{declaring}.{methodName}" : methodName;
                    sb.AppendLine($"{indent}{callPrefix}({argsStr});");
                }
                EmitNextSequentialExec(sb, indentLevel, node, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                break;
        }
    }

    private void EmitNextSequentialExec(
        StringBuilder sb,
        int indentLevel,
        BlueprintNode node,
        Dictionary<string, BlueprintNode> nodeMap,
        Dictionary<string, List<BlueprintConnection>> connectionsFromPin,
        Dictionary<string, BlueprintConnection> connectionsToPin,
        HashSet<string> visitedInChain)
    {
        var execOut = node.Outputs.FirstOrDefault(p => p.Type == BlueprintPinType.Exec);
        if (execOut != null)
        {
            var key = $"{node.Id}_{execOut.Id}";
            if (connectionsFromPin.TryGetValue(key, out var conns))
            {
                foreach (var conn in conns)
                {
                    if (nodeMap.TryGetValue(conn.ToNodeId, out var nextNode))
                    {
                        EmitNodeStatement(sb, indentLevel, nextNode, nodeMap, connectionsFromPin, connectionsToPin, visitedInChain);
                    }
                }
            }
        }
    }

    private string ResolveInputPinExpression(
        BlueprintNode node,
        string pinName,
        BlueprintPinType expectedType,
        Dictionary<string, BlueprintNode> nodeMap,
        Dictionary<string, BlueprintConnection> connectionsToPin)
    {
        var pin = node.Inputs.FirstOrDefault(p => p.Name.Equals(pinName, StringComparison.OrdinalIgnoreCase));
        if (pin == null)
        {
            return FormatDefaultLiteral(null, expectedType);
        }

        var key = $"{node.Id}_{pin.Id}";
        if (connectionsToPin.TryGetValue(key, out var conn))
        {
            if (nodeMap.TryGetValue(conn.FromNodeId, out var sourceNode))
            {
                var sourcePin = sourceNode.Outputs.FirstOrDefault(p => p.Id == conn.FromPinId);
                return EvaluatePureExpression(sourceNode, sourcePin, nodeMap, connectionsToPin);
            }
        }

        // Inline value or default
        if (node.Properties.TryGetValue(pin.Name, out var propVal) && !string.IsNullOrWhiteSpace(propVal))
        {
            return FormatDefaultLiteral(propVal, pin.Type);
        }

        return FormatDefaultLiteral(pin.DefaultValue, pin.Type);
    }

    private string EvaluatePureExpression(
        BlueprintNode node,
        BlueprintPin? pin,
        Dictionary<string, BlueprintNode> nodeMap,
        Dictionary<string, BlueprintConnection> connectionsToPin)
    {
        switch (node.NodeType)
        {
            case "GetActorLocation":
                if (pin?.Name == "X") return "GetActorLocation().X";
                if (pin?.Name == "Y") return "GetActorLocation().Y";
                if (pin?.Name == "Z") return "GetActorLocation().Z";
                return "GetActorLocation()";

            case "GetActorRotation":
                if (pin?.Name == "Pitch" || pin?.Name == "X") return "GetActorRotation().X";
                if (pin?.Name == "Yaw" || pin?.Name == "Y") return "GetActorRotation().Y";
                if (pin?.Name == "Roll" || pin?.Name == "Z") return "GetActorRotation().Z";
                return "GetActorRotation()";

            case "GetActorScale":
                return "GetActorScale()";

            case "GetVariable":
                var varName = node.Properties.TryGetValue("VariableName", out var vn) ? SanitizeIdentifier(vn) : "Variable";
                return varName;

            case "MakeVector":
                var x = ResolveInputPinExpression(node, "X", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var y = ResolveInputPinExpression(node, "Y", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var z = ResolveInputPinExpression(node, "Z", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"new Vector3({x}, {y}, {z})";

            case "BreakVector":
                var inVec = ResolveInputPinExpression(node, "In", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                if (pin?.Name == "X") return $"{inVec}.X";
                if (pin?.Name == "Y") return $"{inVec}.Y";
                if (pin?.Name == "Z") return $"{inVec}.Z";
                return inVec;

            case "Add":
                var addA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var addB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({addA} + {addB})";

            case "Subtract":
                var subA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var subB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({subA} - {subB})";

            case "Multiply":
                var mulA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var mulB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({mulA} * {mulB})";

            case "Divide":
                var divA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var divB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({divA} / {divB})";

            case "Lerp":
                var lerpA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var lerpB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var alpha = ResolveInputPinExpression(node, "Alpha", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({lerpA} + ({lerpB} - {lerpA}) * {alpha})";

            case "VectorDistance":
                var v1 = ResolveInputPinExpression(node, "V1", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                var v2 = ResolveInputPinExpression(node, "V2", BlueprintPinType.Vector3, nodeMap, connectionsToPin);
                return $"Vector3.Distance({v1}, {v2})";

            case "CompareEqual":
                var eqA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var eqB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({eqA} == {eqB})";

            case "CompareNotEqual":
                var neqA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var neqB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({neqA} != {neqB})";

            case "CompareGreater":
                var gtA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var gtB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({gtA} > {gtB})";

            case "CompareLess":
                var ltA = ResolveInputPinExpression(node, "A", BlueprintPinType.Float, nodeMap, connectionsToPin);
                var ltB = ResolveInputPinExpression(node, "B", BlueprintPinType.Float, nodeMap, connectionsToPin);
                return $"({ltA} < {ltB})";

            case "LogicalAnd":
                var andA = ResolveInputPinExpression(node, "A", BlueprintPinType.Boolean, nodeMap, connectionsToPin);
                var andB = ResolveInputPinExpression(node, "B", BlueprintPinType.Boolean, nodeMap, connectionsToPin);
                return $"({andA} && {andB})";

            case "LogicalOr":
                var orA = ResolveInputPinExpression(node, "A", BlueprintPinType.Boolean, nodeMap, connectionsToPin);
                var orB = ResolveInputPinExpression(node, "B", BlueprintPinType.Boolean, nodeMap, connectionsToPin);
                return $"({orA} || {orB})";

            case "LogicalNot":
                var notA = ResolveInputPinExpression(node, "A", BlueprintPinType.Boolean, nodeMap, connectionsToPin);
                return $"(!{notA})";

            case "EventTick":
                if (pin?.Name.Equals("DeltaSeconds", StringComparison.OrdinalIgnoreCase) == true)
                {
                    return "deltaSeconds";
                }
                break;

            case "OnCollisionEnter":
            case "OnTriggerEnter":
                if (pin?.Name.Equals("Other", StringComparison.OrdinalIgnoreCase) == true)
                {
                    return "other";
                }
                break;
        }

        // Reflected pure function invocation fallback
        var dataInputs = node.Inputs.Where(p => p.Type != BlueprintPinType.Exec).ToList();
        if (dataInputs.Count > 0 || node.NodeType.Contains('.'))
        {
            var argExprs = dataInputs.Select(p => ResolveInputPinExpression(node, p.Name, p.Type, nodeMap, connectionsToPin));
            var argsStr = string.Join(", ", argExprs);
            var methodName = node.NodeType.Contains('.') ? node.NodeType.Substring(node.NodeType.LastIndexOf('.') + 1) : node.NodeType;
            var declaring = node.Properties.TryGetValue("DeclaringTypeShort", out var dt) ? dt : "";
            var isStatic = !node.Properties.TryGetValue("IsStatic", out var isSt) || isSt == "true";
            var prefix = isStatic && !string.IsNullOrEmpty(declaring) ? $"{declaring}.{methodName}" : methodName;
            return $"{prefix}({argsStr})";
        }

        return FormatDefaultLiteral(pin?.DefaultValue, pin?.Type ?? BlueprintPinType.Float);
    }

    private static string MapPinTypeToCSharp(BlueprintPinType type) => type switch
    {
        BlueprintPinType.Exec => "void",
        BlueprintPinType.Boolean => "bool",
        BlueprintPinType.Integer => "int",
        BlueprintPinType.Float => "float",
        BlueprintPinType.Vector3 => "Vector3",
        BlueprintPinType.String => "string",
        BlueprintPinType.ActorRef => "Actor?",
        _ => "object"
    };

    private static string FormatDefaultLiteral(string? value, BlueprintPinType type)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return type switch
            {
                BlueprintPinType.Boolean => "false",
                BlueprintPinType.Integer => "0",
                BlueprintPinType.Float => "0.0f",
                BlueprintPinType.Vector3 => "Vector3.Zero",
                BlueprintPinType.String => "\"\"",
                BlueprintPinType.ActorRef => "null",
                _ => "null"
            };
        }

        return type switch
        {
            BlueprintPinType.Boolean => bool.TryParse(value, out var b) ? (b ? "true" : "false") : "false",
            BlueprintPinType.Integer => int.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var i) ? i.ToString(CultureInfo.InvariantCulture) : "0",
            BlueprintPinType.Float => float.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var f) ? $"{f.ToString("G", CultureInfo.InvariantCulture)}f" : "0.0f",
            BlueprintPinType.Vector3 => value.StartsWith("new", StringComparison.OrdinalIgnoreCase) ? value : "Vector3.Zero",
            BlueprintPinType.String => $"\"{value.Replace("\"", "\\\"")}\"",
            BlueprintPinType.ActorRef => "null",
            _ => value
        };
    }

    private static string SanitizeIdentifier(string? name)
    {
        if (string.IsNullOrWhiteSpace(name)) return "Item";
        var sanitized = SanitizeIdentifierRegex().Replace(name, "_");
        if (char.IsDigit(sanitized[0])) sanitized = "_" + sanitized;
        return sanitized;
    }
